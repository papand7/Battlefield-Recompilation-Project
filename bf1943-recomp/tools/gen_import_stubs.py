"""Writes logged stub implementations for every import the recompiled code uses
that runtime/*.cpp does not implement yet.

Usage: gen_import_stubs.py <ppc_recomp_shared.h> <runtime dir> <out.cpp>
The output only lists Xbox API names; it is still written to the build folder.
"""
import pathlib
import re
import sys

shared, runtime_dir, out = sys.argv[1:4]
imports = sorted(set(re.findall(r"PPC_EXTERN_FUNC\(__imp__(\w+)\)", pathlib.Path(shared).read_text())))
imports = [n for n in imports if not n.startswith("sub_")]
implemented = set()
for f in pathlib.Path(runtime_dir).glob("*.cpp"):
    implemented |= set(re.findall(r"(?:GUEST_IMPORT|XMA_IMPORT\d)\((\w+)\)", f.read_text(encoding="utf-8")))

lines = ['// Generated by tools/gen_import_stubs.py: imports with no implementation yet.',
         '#include "guest.h"', '']
missing = [n for n in imports if n not in implemented]
for n in missing:
    lines.append(f'GUEST_IMPORT({n}) {{ static std::atomic<bool> once; '
                 f'if (!once.exchange(true)) RT_WARN("unimplemented import {n} (r3=%08X r4=%08X)", ARG32(3), ARG32(4)); '
                 f'RETURN(0); }}')
text = "\n".join(lines) + "\n"
p = pathlib.Path(out)
if not p.exists() or p.read_text() != text:
    p.write_text(text)
print(f"imports: {len(imports)}, implemented: {len(imports) - len(missing)}, stubbed: {len(missing)}")
