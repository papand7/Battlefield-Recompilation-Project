"""Compiles Xenia's internal GPU/UI shaders (thirdparty/xenia/src/xenia/*/shaders)
to SPIR-V C headers under shaders/bytecode/vulkan_spirv/, using the Vulkan SDK's
glslangValidator and spirv-opt (same steps as Xenia's own build).

Usage: build_xenia_shaders.py <thirdparty/xenia/src> <out include dir>
Output goes to <out>/xenia/{gpu,ui}/shaders/bytecode/vulkan_spirv/<name>.h.
"""
import os
import pathlib
import subprocess
import sys
import tempfile

STAGES = {"vs": "vert", "hs": "tesc", "ds": "tese", "gs": "geom", "ps": "frag", "cs": "comp"}
XESL_WRAPPER = ('#version 460\n'
                '#extension GL_EXT_control_flow_attributes : require\n'
                '#extension GL_EXT_samplerless_texture_functions : require\n'
                '#extension GL_GOOGLE_include_directive : require\n'
                '#include "{}"\n')

# Extra builds of a shader with other defines: name -> [(ident, glslang args)].
VARIANTS = {"scene_fx.cs.glsl": [("scene_fx_rt_cs", ["-DSCENE_FX_RT=1", "--target-env", "vulkan1.2"])]}

src_root, out_root = map(pathlib.Path, sys.argv[1:3])
sdk_bin = pathlib.Path(os.environ["VULKAN_SDK"]) / "Bin"
glslang, spirv_opt = sdk_bin / "glslangValidator.exe", sdk_bin / "spirv-opt.exe"

built = failed = 0
for src in sorted(src_root.glob("xenia/*/shaders/*")):
    name = src.name
    if not (name.endswith(".glsl") or name.endswith(".xesl")) or len(name) <= 8 or name[-8] != ".":
        continue
    base_ident = name[:-5].replace(".", "_")
    if base_ident[-2:] not in STAGES:
        continue
    for ident, extra in [(base_ident, [])] + VARIANTS.get(name, []):
        rel = src.parent.relative_to(src_root)
        out = out_root / rel / "bytecode" / "vulkan_spirv" / f"{ident}.h"
        if out.exists() and out.stat().st_mtime >= max(p.stat().st_mtime for p in src.parent.iterdir() if p.is_file()):
            continue
        out.parent.mkdir(parents=True, exist_ok=True)
        with tempfile.TemporaryDirectory() as tmp:
            raw, opt = pathlib.Path(tmp, "a.spv"), pathlib.Path(tmp, "b.spv")
            xesl = name.endswith(".xesl")
            args = [str(glslang), "--stdin" if xesl else str(src), "-DSHADING_LANGUAGE_GLSL_XE=1",
                    "-S", STAGES[ident[-2:]], "-o", str(raw), "-V"] + extra
            if xesl:
                args.append(f"-I{src.parent}")
            r = subprocess.run(args, input=XESL_WRAPPER.format(name) if xesl else None, text=True,
                               capture_output=True)
            if r.returncode == 0:
                r = subprocess.run([str(spirv_opt), "-O", "-O", "--canonicalize-ids", str(raw), "-o", str(opt)],
                                   capture_output=True, text=True)
            if r.returncode != 0:
                print(f"FAILED {src}\n{r.stdout}{r.stderr}")
                failed += 1
                continue
            words = opt.read_bytes()
            body = ",".join(("\n    " if i % 6 == 0 else " ") + "0x%08X" % int.from_bytes(words[i * 4:i * 4 + 4], "little")
                            for i in range(len(words) // 4))
            out.write_text(f"// Generated by tools/build_xenia_shaders.py from {name}.\n"
                           f"const uint32_t {ident}[] = {{{body},\n}};\n")
            built += 1
print(f"shaders built: {built}, failed: {failed}")
sys.exit(1 if failed else 0)
